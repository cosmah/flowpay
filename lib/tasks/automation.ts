import { snapshotFromDraft } from "@/lib/library/snapshot"
import type { Draft, LibraryItem, Task } from "@/types"

const DAY_MS = 24 * 60 * 60 * 1000

function draftTitle(draft: Draft) {
  return `${draft.format} draft`
}

function isOpenReviewTask(task: Task, draftId: string) {
  return (
    task.draftId === draftId &&
    task.type === "review" &&
    task.status !== "done"
  )
}

type TaskMutators = {
  tasks: Task[]
  addTask: (task: Omit<Task, "id" | "createdAt"> & { id?: string }) => Task
  updateTask: (id: string, patch: Partial<Task>) => Task | undefined
}

export type LibraryApprovalContext = {
  items: LibraryItem[]
  addItem: (
    item: Omit<LibraryItem, "id"> & { id?: string }
  ) => LibraryItem
  campaignName: string
  reviewer: string
}

export type DraftSubmitContext = {
  /** First / assigned reviewer — owns the review task. */
  reviewerName: string
}

export type ChangesRequestedContext = {
  /** Draft author (marketer) — owns the revise task. */
  authorName: string
}

/** When a draft is submitted: create one open review task (due +24h) if none exists. */
export function onDraftSubmitted(
  draft: Draft,
  store: TaskMutators,
  ctx: DraftSubmitContext
) {
  const exists = store.tasks.some((task) => isOpenReviewTask(task, draft.id))
  if (exists) return null

  const now = new Date()
  return store.addTask({
    campaignId: draft.campaignId,
    draftId: draft.id,
    title: `Review: ${draftTitle(draft)}`,
    type: "review",
    owner: ctx.reviewerName,
    dueDate: new Date(now.getTime() + DAY_MS).toISOString(),
    status: "todo",
    autoGenerated: true,
  })
}

/** When changes are requested: complete open review task, create revise task for marketer. */
export function onChangesRequested(
  draft: Draft,
  store: TaskMutators,
  ctx: ChangesRequestedContext
) {
  const openReview = store.tasks.find((task) => isOpenReviewTask(task, draft.id))
  if (openReview) {
    store.updateTask(openReview.id, {
      status: "done",
      completedAt: new Date().toISOString(),
    })
  }

  const now = new Date()
  return store.addTask({
    campaignId: draft.campaignId,
    draftId: draft.id,
    title: `Revise: ${draftTitle(draft)}`,
    type: "revise",
    owner: ctx.authorName,
    dueDate: new Date(now.getTime() + DAY_MS).toISOString(),
    status: "todo",
    autoGenerated: true,
  })
}

/**
 * When a draft is approved: complete its open review task and (when library
 * context is provided) add a frozen library snapshot. Never duplicates.
 */
export function onDraftApproved(
  draft: Draft,
  store: TaskMutators,
  library?: LibraryApprovalContext
) {
  const openReview = store.tasks.find((task) => isOpenReviewTask(task, draft.id))
  if (openReview) {
    store.updateTask(openReview.id, {
      status: "done",
      completedAt: new Date().toISOString(),
    })
  }

  if (!library) return undefined
  if (draft.status !== "approved") return undefined
  if (library.items.some((item) => item.draftId === draft.id)) return undefined

  return library.addItem(
    snapshotFromDraft(draft, library.campaignName, library.reviewer)
  )
}
