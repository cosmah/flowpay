import { createSeedMembers } from "@/lib/team/seed"
import type { Task } from "@/types"

/** First-load demo seed: 3 tasks / 2 campaigns, one overdue manual, one done. */
export function createSeedTasks(now = new Date()): Task[] {
  const day = 24 * 60 * 60 * 1000
  const [amina, jordan] = createSeedMembers()

  return [
    {
      id: "task_seed_review_caption",
      campaignId: "camp_summer_launch",
      draftId: "draft_summer_caption",
      title: "Review: caption draft",
      type: "review",
      owner: jordan.name,
      dueDate: new Date(now.getTime() + day).toISOString(),
      status: "todo",
      autoGenerated: true,
      createdAt: now.toISOString(),
    },
    {
      id: "task_seed_overdue_manual",
      campaignId: "camp_summer_launch",
      title: "Confirm summer visual assets with brand",
      type: "manual",
      owner: amina.name,
      dueDate: new Date(now.getTime() - day).toISOString(),
      status: "todo",
      autoGenerated: false,
      createdAt: new Date(now.getTime() - 2 * day).toISOString(),
    },
    {
      id: "task_seed_done_onboarding",
      campaignId: "camp_onboarding",
      draftId: "draft_onboard_email",
      title: "Review: email draft",
      type: "review",
      owner: jordan.name,
      dueDate: new Date(now.getTime() - 2 * day).toISOString(),
      status: "done",
      autoGenerated: true,
      createdAt: new Date(now.getTime() - 3 * day).toISOString(),
      completedAt: new Date(now.getTime() - day).toISOString(),
    },
  ]
}
