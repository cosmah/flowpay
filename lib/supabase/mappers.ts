import type {
  Campaign,
  CampaignBrief,
  CampaignStatus,
  Draft,
  DraftFormat,
  LibraryItem,
  LibraryItemType,
  Project,
  Task,
  TaskStatus,
  TaskType,
  TestSendLog,
} from "@/types"
import type { Tables } from "./types"

export function projectFromRow(row: Tables<"projects">): Project {
  return {
    id: row.id,
    name: row.name,
    description: row.description,
    status: row.status,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    createdBy: row.created_by ?? "unknown",
  }
}

export function channelsFromDb(channel: string): string[] {
  return channel
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean)
}

export function channelsToDb(channels: string[]): string {
  return channels.join(", ")
}

export function campaignFromRow(row: Tables<"campaigns">): Campaign {
  const brief: CampaignBrief = {
    title: row.title,
    objective: row.objective,
    audience: row.audience,
    productService: row.product,
    tone: row.tone,
    customerAction: row.cta,
    channels: channelsFromDb(row.channel),
  }

  const status: CampaignStatus =
    row.status === "archived" ? "approved" : (row.status as CampaignStatus)

  return {
    id: row.id,
    projectId: row.project_id ?? "",
    brief,
    status,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    createdBy: row.owner_email ?? "unknown",
  }
}

export function campaignBriefToRow(brief: CampaignBrief) {
  return {
    title: brief.title,
    objective: brief.objective,
    audience: brief.audience,
    product: brief.productService,
    channel: channelsToDb(brief.channels),
    tone: brief.tone,
    cta: brief.customerAction,
  }
}

const DRAFT_FORMAT: Record<string, DraftFormat> = {
  social_caption: "caption",
  email: "email",
  graphic: "visual",
}

const CONTENT_TYPE: Record<DraftFormat, "social_caption" | "email" | "graphic"> =
  {
    caption: "social_caption",
    email: "email",
    visual: "graphic",
  }

export function draftFromContentItem(
  row: Tables<"content_items">,
  reviews: Tables<"reviews">[] = []
): Draft {
  return {
    id: row.id,
    campaignId: row.campaign_id,
    format: DRAFT_FORMAT[row.type] ?? "caption",
    content: row.body,
    status: row.status,
    generationSource: "template",
    reviewComments: reviews
      .filter((review) => review.content_item_id === row.id && review.feedback)
      .map((review) => ({
        id: review.id,
        authorRole: "reviewer" as const,
        body: review.feedback ?? "",
        createdAt: review.created_at,
      })),
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  }
}

export function contentTypeFromFormat(format: DraftFormat) {
  return CONTENT_TYPE[format]
}

const TASK_STATUS_FROM: Record<string, TaskStatus> = {
  pending: "todo",
  in_progress: "in_progress",
  completed: "done",
  blocked: "todo",
}

const TASK_STATUS_TO: Record<TaskStatus, "pending" | "in_progress" | "completed" | "blocked"> =
  {
    todo: "pending",
    in_progress: "in_progress",
    done: "completed",
  }

export function taskFromRow(row: Tables<"tasks">): Task {
  const title = row.title
  let type: TaskType = "manual"
  if (/review/i.test(title)) type = "review"
  else if (/revis|change/i.test(title)) type = "revise"

  return {
    id: row.id,
    campaignId: row.campaign_id,
    draftId: row.content_item_id ?? undefined,
    title: row.title,
    type,
    owner: row.owner_email ?? "Unassigned",
    dueDate: row.due_date
      ? new Date(row.due_date).toISOString()
      : new Date().toISOString(),
    status: TASK_STATUS_FROM[row.status] ?? "todo",
    autoGenerated: row.automated,
    createdAt: row.created_at,
    completedAt:
      row.status === "completed" ? row.updated_at : undefined,
  }
}

export function taskStatusToRow(status: TaskStatus) {
  return TASK_STATUS_TO[status]
}

const LIBRARY_TYPE: Record<string, LibraryItemType> = {
  social_caption: "caption",
  email: "email",
  graphic: "graphic",
}

export function libraryFromRow(
  row: Tables<"library">,
  campaignName = "Campaign"
): LibraryItem {
  return {
    id: row.id,
    campaignId: row.campaign_id,
    campaignName,
    draftId: row.content_item_id ?? row.id,
    type: LIBRARY_TYPE[row.type] ?? "caption",
    title: row.title,
    content: row.body,
    approvedBy: row.approved_by ?? "Reviewer",
    approvedAt: row.approved_at,
    tags: row.tags ?? undefined,
  }
}

export function testSendFromRow(row: Tables<"test_sends">): TestSendLog {
  return {
    id: row.id,
    libraryItemId: row.library_item_id,
    mode: row.method === "resend" ? "resend" : "simulated",
    result: row.status === "error" ? "error" : "submitted",
    message: row.error_message ?? `${row.method}: ${row.status}`,
    createdAt: row.sent_at,
  }
}

export function defaultContentBodies(brief: CampaignBrief) {
  const product = brief.productService
  const cta = brief.customerAction
  return {
    social_caption: `We are proud to introduce ${product}!\n\nPerfect for ${brief.audience}.\n\n👉 ${cta}\n\n#${product.replace(/\s+/g, "")} #NewLaunch`,
    email: `Subject: Introducing ${brief.title}\n\nHi there,\n\n${brief.objective}\n\n${product} helps ${brief.audience}.\n\n${cta} today.\n\n— The team`,
    graphic: JSON.stringify({
      version: 1,
      kind: "visual",
      product,
      cta,
      background: "#0f766e",
      button: { mode: "solid", color: "#ffffff" },
      buttonTextColor: "#0f766e",
    }),
  }
}
