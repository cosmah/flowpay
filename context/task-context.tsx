"use client"

import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
  type ReactNode,
} from "react"
import {
  onChangesRequested,
  onDraftApproved,
  onDraftSubmitted,
  type LibraryApprovalContext,
} from "@/lib/tasks/automation"
import { createSeedTasks } from "@/lib/tasks/seed"
import type { Draft, Task, TaskWithMeta } from "@/types"
import { withTaskMeta } from "@/types"

const STORAGE_KEY = "flowpay.tasks.v1"
const SEEDED_KEY = "flowpay.tasks.seeded"

type NewTaskInput = Omit<Task, "id" | "createdAt"> & {
  id?: string
  createdAt?: string
}

interface TaskContextValue {
  tasks: TaskWithMeta[]
  addTask: (input: NewTaskInput) => Task
  updateTask: (id: string, patch: Partial<Task>) => Task | undefined
  getTasksByCampaign: (campaignId: string) => TaskWithMeta[]
  handleDraftSubmitted: (draft: Draft) => void
  handleChangesRequested: (draft: Draft) => void
  handleDraftApproved: (
    draft: Draft,
    library?: LibraryApprovalContext
  ) => void
}

const TaskContext = createContext<TaskContextValue | null>(null)

function readStoredTasks(): Task[] | null {
  if (typeof window === "undefined") return null
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY)
    if (!raw) return null
    return JSON.parse(raw) as Task[]
  } catch {
    return null
  }
}

function writeStoredTasks(tasks: Task[]) {
  if (typeof window === "undefined") return
  window.localStorage.setItem(STORAGE_KEY, JSON.stringify(tasks))
}

function applyCompletedAt(task: Task, patch: Partial<Task>): Task {
  const nextStatus = patch.status ?? task.status
  const completedAt =
    nextStatus === "done"
      ? (patch.completedAt ?? task.completedAt ?? new Date().toISOString())
      : patch.status
        ? undefined
        : (patch.completedAt ?? task.completedAt)

  return { ...task, ...patch, completedAt }
}

export function TaskProvider({ children }: { children: ReactNode }) {
  const [tasks, setTasks] = useState<Task[]>([])
  const [ready, setReady] = useState(false)
  const tasksRef = useRef<Task[]>([])

  const commit = useCallback((next: Task[]) => {
    tasksRef.current = next
    setTasks(next)
    writeStoredTasks(next)
  }, [])

  useEffect(() => {
    const stored = readStoredTasks()
    const seeded = window.localStorage.getItem(SEEDED_KEY) === "1"

    if (stored && stored.length > 0) {
      tasksRef.current = stored
      setTasks(stored)
    } else if (!seeded) {
      const seed = createSeedTasks()
      tasksRef.current = seed
      setTasks(seed)
      writeStoredTasks(seed)
      window.localStorage.setItem(SEEDED_KEY, "1")
    } else {
      const empty = stored ?? []
      tasksRef.current = empty
      setTasks(empty)
    }
    setReady(true)
  }, [])

  const addTask = useCallback(
    (input: NewTaskInput) => {
      const now = new Date().toISOString()
      const task: Task = {
        id: input.id ?? `task_${crypto.randomUUID().slice(0, 8)}`,
        campaignId: input.campaignId,
        draftId: input.draftId,
        title: input.title,
        type: input.type,
        owner: input.owner,
        dueDate: input.dueDate,
        status: input.status,
        autoGenerated: input.autoGenerated,
        createdAt: input.createdAt ?? now,
        completedAt: input.completedAt,
      }
      commit([task, ...tasksRef.current])
      return task
    },
    [commit]
  )

  const updateTask = useCallback(
    (id: string, patch: Partial<Task>) => {
      let updated: Task | undefined
      const next = tasksRef.current.map((task) => {
        if (task.id !== id) return task
        updated = applyCompletedAt(task, patch)
        return updated
      })
      commit(next)
      return updated
    },
    [commit]
  )

  const getTasksByCampaign = useCallback(
    (campaignId: string) =>
      tasksRef.current
        .filter((task) => task.campaignId === campaignId)
        .map((task) => withTaskMeta(task)),
    [tasks]
  )

  const storeApi = useMemo(
    () => ({
      get tasks() {
        return tasksRef.current
      },
      addTask,
      updateTask,
    }),
    [addTask, updateTask]
  )

  const handleDraftSubmitted = useCallback(
    (draft: Draft) => {
      onDraftSubmitted(draft, storeApi)
    },
    [storeApi]
  )

  const handleChangesRequested = useCallback(
    (draft: Draft) => {
      onChangesRequested(draft, storeApi)
    },
    [storeApi]
  )

  const handleDraftApproved = useCallback(
    (draft: Draft, library?: LibraryApprovalContext) => {
      onDraftApproved(draft, storeApi, library)
    },
    [storeApi]
  )

  const value = useMemo<TaskContextValue>(
    () => ({
      tasks: tasks.map((task) => withTaskMeta(task)),
      addTask,
      updateTask,
      getTasksByCampaign,
      handleDraftSubmitted,
      handleChangesRequested,
      handleDraftApproved,
    }),
    [
      tasks,
      addTask,
      updateTask,
      getTasksByCampaign,
      handleDraftSubmitted,
      handleChangesRequested,
      handleDraftApproved,
    ]
  )

  if (!ready) {
    return <TaskContext.Provider value={value}>{children}</TaskContext.Provider>
  }

  return <TaskContext.Provider value={value}>{children}</TaskContext.Provider>
}

export function useTasks() {
  const ctx = useContext(TaskContext)
  if (!ctx) {
    throw new Error("useTasks must be used within TaskProvider")
  }
  return ctx
}
