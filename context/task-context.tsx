"use client"

import {
  createContext,
  useCallback,
  useContext,
  useMemo,
  type ReactNode,
} from "react"
import { useDb } from "@/hooks/use-db"
import { createClient } from "@/lib/supabase/client"
import { taskFromRow, taskStatusToRow } from "@/lib/supabase/mappers"
import type {
  ChangesRequestedContext,
  DraftSubmitContext,
  LibraryApprovalContext,
} from "@/lib/tasks/automation"
import type { Draft, Task, TaskWithMeta } from "@/types"
import { withTaskMeta } from "@/types"

type NewTaskInput = Omit<Task, "id" | "createdAt"> & {
  id?: string
  createdAt?: string
}

interface TaskContextValue {
  tasks: TaskWithMeta[]
  addTask: (input: NewTaskInput) => Promise<Task>
  updateTask: (id: string, patch: Partial<Task>) => Promise<Task | undefined>
  getTasksByCampaign: (campaignId: string) => TaskWithMeta[]
  handleDraftSubmitted: (draft: Draft, ctx: DraftSubmitContext) => void
  handleChangesRequested: (draft: Draft, ctx: ChangesRequestedContext) => void
  handleDraftApproved: (
    draft: Draft,
    library?: LibraryApprovalContext
  ) => void
}

const TaskContext = createContext<TaskContextValue | null>(null)

function toOwnerEmail(owner: string) {
  const value = owner.trim()
  return value.includes("@") ? value.toLowerCase() : null
}

export function TaskProvider({ children }: { children: ReactNode }) {
  const { db, refresh } = useDb()

  const tasks = useMemo(
    () => db.tasks.map((task) => withTaskMeta(task)),
    [db.tasks]
  )

  const addTask = useCallback(
    async (input: NewTaskInput) => {
      const supabase = createClient()
      const {
        data: { user },
      } = await supabase.auth.getUser()
      const { data: profile } = user
        ? await supabase
            .from("profiles")
            .select("company_id")
            .eq("id", user.id)
            .maybeSingle()
        : { data: null }

      if (!profile?.company_id) {
        throw new Error("Join or create a company before adding tasks.")
      }

      const { data: campaign } = await supabase
        .from("campaigns")
        .select("id")
        .eq("id", input.campaignId)
        .eq("company_id", profile.company_id)
        .maybeSingle()

      if (!campaign) {
        throw new Error("Campaign not found for your company.")
      }

      const ownerEmail = toOwnerEmail(input.owner)
      if (!ownerEmail) {
        throw new Error("Select a team member with a valid email as owner.")
      }

      const due = input.dueDate.slice(0, 10)
      const { data, error } = await supabase
        .from("tasks")
        .insert({
          campaign_id: input.campaignId,
          content_item_id: input.draftId ?? null,
          title: input.title,
          owner_email: ownerEmail,
          due_date: due,
          status: taskStatusToRow(input.status),
          automated: input.autoGenerated,
          company_id: profile.company_id,
        })
        .select("*")
        .single()

      if (error || !data) {
        throw new Error(error?.message ?? "Could not create task")
      }

      await refresh()
      return taskFromRow(data)
    },
    [refresh]
  )

  const updateTask = useCallback(
    async (id: string, patch: Partial<Task>) => {
      const supabase = createClient()
      const updates: {
        title?: string
        owner_email?: string | null
        due_date?: string
        status?: ReturnType<typeof taskStatusToRow>
        automated?: boolean
        updated_at: string
      } = {
        updated_at: new Date().toISOString(),
      }
      if (patch.title) updates.title = patch.title
      if (patch.owner !== undefined) {
        updates.owner_email = toOwnerEmail(patch.owner)
      }
      if (patch.dueDate) updates.due_date = patch.dueDate.slice(0, 10)
      if (patch.status) updates.status = taskStatusToRow(patch.status)
      if (typeof patch.autoGenerated === "boolean") {
        updates.automated = patch.autoGenerated
      }

      const { data, error } = await supabase
        .from("tasks")
        .update(updates)
        .eq("id", id)
        .select("*")
        .single()

      if (error || !data) return undefined
      await refresh()
      return taskFromRow(data)
    },
    [refresh]
  )

  const getTasksByCampaign = useCallback(
    (campaignId: string) =>
      tasks.filter((task) => task.campaignId === campaignId),
    [tasks]
  )

  // Workflow hooks: db-context already creates/updates tasks in Supabase.
  const handleDraftSubmitted = useCallback(
    (_draft: Draft, _ctx: DraftSubmitContext) => {
      void refresh()
    },
    [refresh]
  )

  const handleChangesRequested = useCallback(
    (_draft: Draft, _ctx: ChangesRequestedContext) => {
      void refresh()
    },
    [refresh]
  )

  const handleDraftApproved = useCallback(
    (_draft: Draft, _library?: LibraryApprovalContext) => {
      void refresh()
    },
    [refresh]
  )

  const value = useMemo(
    () => ({
      tasks,
      addTask,
      updateTask,
      getTasksByCampaign,
      handleDraftSubmitted,
      handleChangesRequested,
      handleDraftApproved,
    }),
    [
      tasks,
      addTask,
      updateTask,
      getTasksByCampaign,
      handleDraftSubmitted,
      handleChangesRequested,
      handleDraftApproved,
    ]
  )

  return <TaskContext.Provider value={value}>{children}</TaskContext.Provider>
}

export function useTasks() {
  const ctx = useContext(TaskContext)
  if (!ctx) {
    throw new Error("useTasks must be used within TaskProvider")
  }
  return ctx
}
