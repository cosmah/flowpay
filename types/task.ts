export type TaskType = "review" | "revise" | "manual"
export type TaskStatus = "todo" | "in_progress" | "done"

export interface Task {
  id: string
  campaignId: string
  draftId?: string
  title: string
  type: TaskType
  owner: string
  dueDate: string
  status: TaskStatus
  autoGenerated: boolean
  createdAt: string
  completedAt?: string
}

export type TaskWithMeta = Task & {
  isOverdue: boolean
}

export function withTaskMeta(task: Task, now = new Date()): TaskWithMeta {
  const isOverdue =
    task.status !== "done" && new Date(task.dueDate).getTime() < now.getTime()
  return { ...task, isOverdue }
}
