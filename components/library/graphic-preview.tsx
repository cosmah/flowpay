"use client"

import { VisualDraftCard } from "@/components/library/visual-draft-card"
import { ensureGraphicMarkup } from "@/lib/library/graphic"
import { parseVisualDraft } from "@/lib/library/visual"
import { cn } from "@/lib/utils"

export function GraphicPreview({
  content,
  title,
  product,
  cta,
  className,
}: {
  content: string
  title?: string
  product?: string
  cta?: string
  className?: string
}) {
  const spec = parseVisualDraft(content, { product, cta, title })
  if (spec) {
    return (
      <VisualDraftCard
        content={content}
        title={title}
        product={product}
        cta={cta}
        className={className}
      />
    )
  }

  const markup = ensureGraphicMarkup(content, title)
  if (markup.startsWith("data:image")) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img src={markup} alt={title ?? "Graphic"} className={className} />
    )
  }

  return (
    <div
      className={cn(className)}
      // Snapshot SVG only — content is authored/generated by the app.
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  )
}
