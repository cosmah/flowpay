"use client"

import { useEffect, useState, type FormEvent } from "react"
import { toast } from "sonner"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { useTasks } from "@/hooks/use-tasks"
import { useTeam } from "@/hooks/use-team"
import { handleClientError } from "@/lib/errors"
import { cn } from "@/lib/utils"

export function AddTaskForm({
  campaignId,
  campaigns,
  onSuccess,
  compact = false,
}: {
  campaignId?: string
  campaigns: { id: string; title: string }[]
  onSuccess?: () => void
  compact?: boolean
}) {
  const { addTask } = useTasks()
  const { members, currentUser } = useTeam()
  const [title, setTitle] = useState("")
  const [ownerEmail, setOwnerEmail] = useState(currentUser.email)
  const [dueDate, setDueDate] = useState("")
  const [selectedCampaignId, setSelectedCampaignId] = useState(
    campaignId ?? campaigns[0]?.id ?? ""
  )
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    if (!members.some((member) => member.email === ownerEmail)) {
      setOwnerEmail(currentUser.email)
    }
  }, [members, currentUser.email, ownerEmail])

  function onSubmit(event: FormEvent) {
    event.preventDefault()
    const missing: string[] = []
    if (!title.trim()) missing.push("title")
    if (!ownerEmail.trim()) missing.push("owner")
    if (!dueDate) missing.push("due date")
    if (!campaignId && !selectedCampaignId) missing.push("campaign")

    if (missing.length > 0) {
      setError(`Missing ${missing.join(", ")}.`)
      return
    }

    void (async () => {
      try {
        const due = new Date(dueDate)
        await addTask({
          campaignId: campaignId ?? selectedCampaignId,
          title: title.trim(),
          type: "manual",
          owner: ownerEmail.trim(),
          dueDate: due.toISOString(),
          status: "todo",
          autoGenerated: false,
        })
        setTitle("")
        setDueDate("")
        setError(null)
        toast.success("Task added.")
        onSuccess?.()
      } catch (err) {
        handleClientError(err)
      }
    })()
  }

  return (
    <form
      onSubmit={onSubmit}
      className={cn(
        "space-y-4",
        !compact &&
          "rounded-2xl border border-border/70 bg-[var(--rx-paper)] px-5 py-5"
      )}
    >
      {!compact ? (
        <div>
          <h3 className="font-heading text-lg text-[var(--rx-ink)]">Add task</h3>
          <p className="mt-1 text-sm text-muted-foreground">
            Create a manual task for this workflow.
          </p>
        </div>
      ) : null}

      <div className="grid gap-4 sm:grid-cols-2">
        <div className="space-y-2 sm:col-span-2">
          <Label htmlFor="task-title">Title</Label>
          <Input
            id="task-title"
            value={title}
            onChange={(e) => setTitle(e.target.value)}
            placeholder="Confirm assets with brand"
          />
        </div>

        {!campaignId ? (
          <div className="space-y-2 sm:col-span-2">
            <Label htmlFor="task-campaign">Campaign</Label>
            <select
              id="task-campaign"
              value={selectedCampaignId}
              onChange={(e) => setSelectedCampaignId(e.target.value)}
              className="h-10 w-full rounded-lg border border-input bg-transparent px-2.5 text-sm outline-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
            >
              {campaigns.map((campaign) => (
                <option key={campaign.id} value={campaign.id}>
                  {campaign.title}
                </option>
              ))}
            </select>
          </div>
        ) : null}

        <div className="space-y-2">
          <Label htmlFor="task-owner">Owner</Label>
          <select
            id="task-owner"
            value={ownerEmail}
            onChange={(e) => setOwnerEmail(e.target.value)}
            className="h-10 w-full rounded-lg border border-input bg-transparent px-2.5 text-sm outline-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
          >
            <option value="">Select owner</option>
            {members
              .filter((member) => member.status === "active")
              .map((member) => (
                <option key={member.id} value={member.email}>
                  {member.name} ({member.role})
                </option>
              ))}
          </select>
        </div>

        <div className="space-y-2">
          <Label htmlFor="task-due">Due date</Label>
          <Input
            id="task-due"
            type="datetime-local"
            value={dueDate}
            onChange={(e) => setDueDate(e.target.value)}
          />
        </div>
      </div>

      {error ? (
        <p className="text-sm text-destructive" role="alert">
          {error}
        </p>
      ) : null}

      <Button type="submit">Add task</Button>
    </form>
  )
}
